# Makes source/map_data.c: a land bitmap and a city list from Natural Earth (public domain).
import json, sys, unicodedata
from PIL import Image, ImageDraw
land_path, places_path, out_path = sys.argv[1:4]
RES = 4            # cells per degree
LAT0, LAT1 = 84.0, -60.0
W = 360 * RES; H = int((LAT0 - LAT1) * RES)
SS = 2
img = Image.new('L', (W * SS, H * SS), 0)
d = ImageDraw.Draw(img)
def px(lon, lat): return ((lon + 180) * RES * SS, (LAT0 - lat) * RES * SS)
g = json.load(open(land_path))
for f in g['features']:
    geom = f['geometry']
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for poly in polys:
        d.polygon([px(*p[:2]) for p in poly[0]], fill=255)
        for hole in poly[1:]:
            d.polygon([px(*p[:2]) for p in hole], fill=0)
img = img.resize((W, H), Image.BOX)

# Where two separate big pieces of land come within a cell of each other
# (Greenland and Ellesmere, Spain and Morocco), the cells along the join are
# listed so the map can keep a line of water between them however far out
# it is zoomed.
def area(ring):
    a = 0
    for i in range(len(ring)):
        x1, y1 = ring[i][:2]; x2, y2 = ring[i - 1][:2]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2
ids = Image.new('I', (W, H), 0)
di = ImageDraw.Draw(ids)
big = 0
areas = [0]
for f in g['features']:
    geom = f['geometry']
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for poly in polys:
        if area(poly[0]) < 4: continue      # square degrees: real landmasses only
        big += 1
        areas.append(area(poly[0]))
        di.polygon([((p[0] + 180) * RES, (LAT0 - p[1]) * RES) for p in poly[0]], fill=big)
idp = ids.load()
moat = []
for y in range(H):
    for x in range(W):
        a = idp[x, y]
        if not a: continue
        hit = False
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                xx, yy = (x + dx) % W, y + dy
                if 0 <= yy < H:
                    b = idp[xx, yy]
                    # (only where one side is a continent-sized piece, so
                    # island groups may still run together into one shape)
                    if b and b != a and max(areas[a], areas[b]) > 150: hit = True
        if hit: moat.append((y, x))
pix = img.load()
rowbytes = W // 8
bits = bytearray(rowbytes * H)
n = 0
for y in range(H):
    for x in range(W):
        if pix[x, y] >= 96:
            bits[y * rowbytes + x // 8] |= 0x80 >> (x & 7); n += 1
def ascii(s):
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.replace('’', "'").replace('ø','o').replace('Ø','O').replace('ß','ss').replace('æ','ae').replace('Æ','AE').replace('đ','d').replace('ł','l').replace('Ł','L').replace('ı','i')
    return ''.join(c for c in s if 32 <= ord(c) < 127).replace('"', '').strip()
short = {'United States of America': 'USA', 'United Kingdom': 'UK', 'United Arab Emirates': 'UAE',
         'Democratic Republic of the Congo': 'DR Congo', 'Republic of the Congo': 'Congo',
         'Bosnia and Herzegovina': 'Bosnia', 'Central African Republic': 'C. African Rep.',
         'Dominican Republic': 'Dominican Rep.', 'Czechia': 'Czechia', 'Czech Republic': 'Czechia',
         'Ivory Coast': 'Ivory Coast', "Cote d'Ivoire": 'Ivory Coast', 'Papua New Guinea': 'Papua N. Guinea',
         'Trinidad and Tobago': 'Trinidad', 'Federated States of Micronesia': 'Micronesia',
         'The Bahamas': 'Bahamas', 'Republic of Serbia': 'Serbia', 'United Republic of Tanzania': 'Tanzania',
         'East Timor': 'Timor-Leste', 'Macedonia': 'N. Macedonia', 'Kingdom of Saudi Arabia': 'Saudi Arabia'}
pl = json.load(open(places_path))['features']
cities = []
countries = []
for f in pl:
    p = f['properties']
    name = ascii(p['name']); c = ascii(p['adm0name'] or '')
    c = short.get(c, c)
    if not name: continue
    if c not in countries: countries.append(c)
    cities.append((round(p['latitude'] * 100), round(p['longitude'] * 100), int(p['pop_max'] or 0), name, countries.index(c)))
cities.sort(key=lambda t: t[0])
with open(out_path, 'w') as o:
    o.write('/* map_data.c - generated by tools/gen_map.py from Natural Earth (public domain):\n')
    o.write(' * where there is land, and the names of cities. Do not edit. */\n#include "map_data.h"\n\n')
    o.write('const uint8_t map_land_bits[%d] = {\n' % len(bits))
    for i in range(0, len(bits), 24):
        o.write(''.join('%d,' % b for b in bits[i:i+24]) + '\n')
    o.write('};\n\n/* cells (row, column) where two landmasses meet: kept as water */\n')
    o.write('const uint16_t map_moat[%d][2] = {\n' % len(moat))
    for i in range(0, len(moat), 8):
        o.write(''.join('{%d,%d},' % m for m in moat[i:i+8]) + '\n')
    o.write('};\nconst int map_nmoat = %d;\n\nconst char *const map_countries[%d] = {\n' % (len(moat), len(countries)))
    for c in countries: o.write('  "%s",\n' % c)
    o.write('};\n\n/* sorted by latitude */\nconst MapCity map_cities[%d] = {\n' % len(cities))
    for la, lo, pop, name, ci in cities: o.write('  {%d,%d,%d,%d,"%s"},\n' % (la, lo, min(pop//1000, 65535), ci, name))
    o.write('};\n')
print(W, H, n, 'moat', len(moat), 'big', big, len(cities), len(countries), max(len(c[3]) for c in cities), file=sys.stderr)
